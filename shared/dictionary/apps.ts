const amazon = (app: string, category: Category, activity?: string): Entry => ({ company: 'Amazon', app, category, activity });
/** A CDN or a cloud: who carries the bytes ("Amazon", or its product, "Google Cloud"), never whose app they are. */
const carrier = (company: string, product?: string): Entry => ({ company: product ?? company, category: 'cdn', carrier: true });

