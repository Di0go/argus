/** What an entry says; a field left out is taken from the list that includes it (google-ads says Google). */
export interface Entry {
  company?: string;
  app?: string;
  category?: Category;
  activity?: string;
  /** Advertising, tracking or telemetry; by default, what its category says. */
  tracking?: boolean;
  /** A CDN or cloud that carries others' bytes: it never names the app, whatever is under it. */
  carrier?: boolean;
}

